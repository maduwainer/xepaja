import postgres, { type Sql, type TransactionSql } from "postgres";

// Camada de banco do XepaJá sobre PostgreSQL (via Docker, ver compose.yaml).
// Cliente unico (singleton) de postgres.js; queries usam template tags com
// ${} (parametrizacao automatica) e transacoes via sql.begin() com
// SELECT ... FOR UPDATE onde a regra exige atomicidade (reservas).
//
// Datas: colunas temporais sao TIMESTAMPTZ e o driver devolve cada valor ja
// normalizado para string ISO-8601 com Z (ver pgTimestamptzToISO), entao
// todo o codigo existente que compara ISO como string continua valendo.
// COUNT(*) precisa de ::int porque o Postgres conta em bigint.

export type DbClient = Sql | TransactionSql;

function databaseUrl(): string {
  // XEPAJA_TEST=1 (script bun test) usa o banco de teste dedicado para nao
  // apagar o seed de demonstracao do banco de dev.
  const test = process.env.XEPAJA_TEST === "1";
  const url = test
    ? (process.env.DATABASE_URL_TEST ?? "")
    : (process.env.DATABASE_URL ?? "");
  if (!url) {
    throw new Error(
      test
        ? "Defina DATABASE_URL_TEST no .env (ver .env.example) para rodar os testes."
        : "Defina DATABASE_URL no .env (ver .env.example). Local: suba com docker compose up -d db.",
    );
  }
  return url;
}

// Saida textual do Postgres para timestamptz: "2026-10-16 19:00:00.123+00"
// (fracao opcional, offset +HH ou +HHMM). Converte para ISO canonico com Z.
function pgTimestamptzToISO(raw: string): string {
  const m =
    /^(\d{4}-\d{2}-\d{2}) (\d{2}:\d{2}:\d{2}(?:\.\d+)?)([+-]\d{2}(?::?\d{2})?|Z)$/.exec(
      raw.trim(),
    );
  if (!m) return new Date(raw).toISOString();
  let tz = m[3];
  if (tz === "Z") tz = "+00:00";
  else if (/^[+-]\d{2}$/.test(tz)) tz = `${tz}:00`;
  else tz = tz.replace(/^([+-]\d{2})(\d{2})$/, "$1:$2");
  return new Date(`${m[1]}T${m[2]}${tz}`).toISOString();
}

let sql: Sql | null = null;

export function getDb(): Sql {
  if (sql) return sql;
  sql = postgres(databaseUrl(), {
    // migrate() com IF NOT EXISTS gera NOTICEs; fora isto o boot despeja o catalogo no log.
    onnotice: () => {},
    // Chave propria para nao interferir no tratamento padrao de Date.
    types: {
      timestamptz_iso: {
        to: 1184,
        from: [1114, 1184],
        serialize: (x: unknown) =>
          x instanceof Date ? x.toISOString() : String(x),
        parse: pgTimestamptzToISO,
      },
    },
  });
  return sql;
}

export async function closeDb(): Promise<void> {
  if (sql) {
    await sql.end();
    sql = null;
  }
}

// Espera o Postgres aceitar conexoes (watch/dev aguardam antes do migrate).
export async function waitForDb(tries = 30): Promise<void> {
  const db = getDb();
  for (let i = 1; i <= tries; i += 1) {
    try {
      await db`SELECT 1`;
      return;
    } catch {
      if (i === tries) throw new Error("Postgres nao respondeu. Suba com docker compose up -d db.");
      await new Promise((r) => setTimeout(r, 1000));
    }
  }
}

// Schema do MVP (mesmas tabelas e colunas do legado sqlite, tipos PG).
// pending_expires_at ja nasce no DDL (era ALTER aditivo no sqlite).
const DDL = `
    CREATE TABLE IF NOT EXISTS users (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      cpf TEXT NOT NULL,
      email TEXT NOT NULL UNIQUE,
      password_hash TEXT NOT NULL,
      role TEXT NOT NULL CHECK (role IN ('consumer','merchant')),
      search_radius_km DOUBLE PRECISION NOT NULL DEFAULT 10,
      misses_since_unblock INTEGER NOT NULL DEFAULT 0,
      blocked_until TIMESTAMPTZ,
      created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
    );
    CREATE TABLE IF NOT EXISTS establishments (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      owner_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      name TEXT NOT NULL,
      kind TEXT NOT NULL CHECK (kind IN ('feira','mercearia')),
      cnpj TEXT,
      address_text TEXT NOT NULL,
      reference TEXT NOT NULL DEFAULT '',
      hours TEXT NOT NULL DEFAULT '',
      gps_lat DOUBLE PRECISION,
      gps_lng DOUBLE PRECISION,
      gps_captured_at TIMESTAMPTZ,
      created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
    );
    CREATE TABLE IF NOT EXISTS items (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      establishment_id INTEGER NOT NULL REFERENCES establishments(id) ON DELETE CASCADE,
      name TEXT NOT NULL,
      unit TEXT NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT now()
    );
    CREATE TABLE IF NOT EXISTS offers (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      establishment_id INTEGER NOT NULL REFERENCES establishments(id) ON DELETE CASCADE,
      title TEXT NOT NULL,
      kind TEXT NOT NULL CHECK (kind IN ('item','caixa')),
      photo_path TEXT NOT NULL DEFAULT '',
      total_units INTEGER NOT NULL,
      price_cents INTEGER NOT NULL,
      is_free BOOLEAN NOT NULL DEFAULT FALSE,
      address_snapshot TEXT NOT NULL DEFAULT '',
      gps_lat DOUBLE PRECISION,
      gps_lng DOUBLE PRECISION,
      available_from TIMESTAMPTZ NOT NULL,
      pickup_from TIMESTAMPTZ NOT NULL,
      pickup_until TIMESTAMPTZ NOT NULL,
      storage_notes TEXT NOT NULL DEFAULT '',
      state TEXT NOT NULL DEFAULT 'rascunho'
        CHECK (state IN ('rascunho','publicada','esgotada','encerrada','cancelada','expirada')),
      cancel_reason TEXT NOT NULL DEFAULT '',
      created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
    );
    CREATE TABLE IF NOT EXISTS offer_items (
      offer_id INTEGER NOT NULL REFERENCES offers(id) ON DELETE CASCADE,
      item_id INTEGER NOT NULL REFERENCES items(id) ON DELETE RESTRICT,
      qty_per_unit DOUBLE PRECISION NOT NULL,
      PRIMARY KEY (offer_id, item_id)
    );
    CREATE TABLE IF NOT EXISTS reservations (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      consumer_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      offer_id INTEGER NOT NULL REFERENCES offers(id) ON DELETE CASCADE,
      state TEXT NOT NULL DEFAULT 'pendente'
        CHECK (state IN ('pendente','confirmada','recusada','retirada','cancelada','expirada')),
      idempotency_key TEXT NOT NULL UNIQUE,
      pickup_code_hash TEXT NOT NULL DEFAULT '',
      price_cents INTEGER NOT NULL DEFAULT 0,
      address_snapshot TEXT NOT NULL DEFAULT '',
      gps_lat DOUBLE PRECISION,
      gps_lng DOUBLE PRECISION,
      pickup_until TIMESTAMPTZ NOT NULL,
      pending_expires_at TIMESTAMPTZ,
      cancel_reason TEXT NOT NULL DEFAULT '',
      decided_at TIMESTAMPTZ,
      picked_at TIMESTAMPTZ,
      created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
    );
    CREATE TABLE IF NOT EXISTS notices (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      kind TEXT NOT NULL,
      offer_id INTEGER REFERENCES offers(id) ON DELETE SET NULL,
      reservation_id INTEGER REFERENCES reservations(id) ON DELETE SET NULL,
      body TEXT NOT NULL,
      read_at TIMESTAMPTZ,
      created_at TIMESTAMPTZ NOT NULL DEFAULT now()
    );
    CREATE TABLE IF NOT EXISTS password_resets (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      token_hash TEXT NOT NULL UNIQUE,
      expires_at TIMESTAMPTZ NOT NULL,
      used_at TIMESTAMPTZ,
      created_at TIMESTAMPTZ NOT NULL DEFAULT now()
    );
    CREATE TABLE IF NOT EXISTS sessions (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      token_hash TEXT NOT NULL UNIQUE,
      expires_at TIMESTAMPTZ NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT now()
    );
    CREATE TABLE IF NOT EXISTS audit_log (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      entity TEXT NOT NULL,
      entity_id INTEGER NOT NULL,
      action TEXT NOT NULL,
      actor_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
      at TIMESTAMPTZ NOT NULL DEFAULT now()
    );
    CREATE INDEX IF NOT EXISTS idx_offers_establishment ON offers(establishment_id);
    CREATE INDEX IF NOT EXISTS idx_offers_state ON offers(state);
    CREATE INDEX IF NOT EXISTS idx_reservations_consumer ON reservations(consumer_id);
    CREATE INDEX IF NOT EXISTS idx_reservations_offer ON reservations(offer_id);
    CREATE INDEX IF NOT EXISTS idx_notices_user ON notices(user_id);
    CREATE TABLE IF NOT EXISTS push_subscriptions (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      endpoint TEXT NOT NULL UNIQUE,
      p256dh TEXT NOT NULL,
      auth TEXT NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT now()
    );
    CREATE INDEX IF NOT EXISTS idx_push_user ON push_subscriptions(user_id);
  `;

export async function migrate(): Promise<void> {
  await getDb().unsafe(DDL);
}

// Isolamento dos testes: limpa tudo entre arquivos, reiniciando os ids.
export async function truncateAll(): Promise<void> {
  await getDb()`TRUNCATE users, establishments, items, offers, offer_items, reservations, notices, password_resets, sessions, audit_log, push_subscriptions RESTART IDENTITY CASCADE`;
}

if (import.meta.main) {
  await migrate();
  console.log("migrate ok");
  await closeDb();
}
